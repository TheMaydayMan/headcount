const cache = new Map();
/** The spec for an option: {label, hint, type, options, ...}, or {} when nothing is known. */
export function spec(file, path) {
  const k = file + "#" + path;
  if (cache.has(k)) return cache.get(k);
  let s = FILES[file]?.[path];
  if (!s) for (const [re, r] of RULES) if (re.test(path)) { s = r; break; }
  s = s || {};
  cache.set(k, s);
  return s;
}
export const labelOf = (file, path) => spec(file, path).label;
